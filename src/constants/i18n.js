export const normalizeBackofficeLanguage = (value) => {
  const normalized = String(value || "").trim().toLowerCase().slice(0, 2);
  return BACKOFFICE_LANGUAGES.some((language) => language.code === normalized)
    ? normalized
    : "en";
};

export const getInitialBackofficeLanguage = () => {
  if (typeof window === "undefined") return "en";
  return normalizeBackofficeLanguage(
    window.localStorage.getItem(BACKOFFICE_LANGUAGE_STORAGE_KEY) || "en"
  );
};

export const createBackofficeTranslator = (language) => {
  const normalizedLanguage = normalizeBackofficeLanguage(language);
  const dictionary = BACKOFFICE_TRANSLATIONS[normalizedLanguage] || BACKOFFICE_TRANSLATIONS.en;

  return (key) => dictionary[key] || BACKOFFICE_TRANSLATIONS.en[key] || key;
};
