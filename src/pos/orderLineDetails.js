import { getLineChangeRows } from './orderLineChanges';

const array = value => {
  if (Array.isArray(value)) return value;
  try { const parsed = JSON.parse(value); return Array.isArray(parsed) ? parsed : []; }
  catch { return []; }
};
const nameOf = value => String(value?.name || value?.label || value?.code || (typeof value === 'string' ? value : '')).trim();
const positionOf = value => String(value?.placement || value?.side || '').toUpperCase();
const quantityOf = value => value?.quantityLabel || ({ SIMPLE: 'Simple', DOUBLE: 'Doble' }[value?.quantity] || value?.quantity || '');
const placements = { FULL: 'Entera', RIGHT: 'Mitad derecha', LEFT: 'Mitad izquierda' };
const lineName = item => item?.leftName && item?.rightName ? `${item.leftName} / ${item.rightName}` : String(item?.name || item?.pizzaName || item?.title || (item?.pizzaId ? `Producto #${item.pizzaId}` : 'Producto')).trim();
const lineQty = item => {
  const qty = Number(item?.quantity ?? item?.qty ?? item?.cantidad ?? 1);
  return Number.isFinite(qty) && qty > 0 ? qty : 1;
};
export const isSpatialHeading = text => ['FULL', 'DERECHA', 'IZQUIERDA', 'SIN UBICACIÓN'].includes(text) || /^LADO [12](?::|$)/.test(text);

// Only remove labels generated by our own serializer. Preserve unfamiliar legacy text.
function ingredientText(value, grouped = false) {
  const name = nameOf(value);
  const quantity = quantityOf(value);
  const placement = value?.placementLabel || placements[positionOf(value)] || positionOf(value);
  const generated = `${name}: ${[placement, quantity].filter(Boolean).join(' - ')}`;
  if (value?.label && value.label !== name && value.label !== generated) {
    const label = String(value.label).trim();
    return quantity && !label.toLocaleLowerCase('es').includes(String(quantity).toLocaleLowerCase('es')) ? `${label} - ${quantity}` : label;
  }
  const details = [!grouped && placement, quantity].filter(Boolean).join(' - ');
  return name ? `${name}${details ? `: ${details}` : ''}` : '';
}

function spatialRows(item, ingredients, half) {
  const groups = new Map();
  const add = (value, kind) => {
    let position = positionOf(value);
    if (half) position = ({ A: 'LEFT', B: 'RIGHT', ALL: 'FULL' })[position] || position;
    // Legacy removals without a side apply to the complete recipe.
    if (!position && kind === 'removal') position = 'FULL';
    const key = ['FULL', 'LEFT', 'RIGHT'].includes(position) ? position : 'UNKNOWN';
    const detail = ingredientText(value, key !== 'UNKNOWN');
    if (!detail) return;
    const text = kind === 'removal' ? `SIN ${detail.toLocaleUpperCase('es')}` : kind === 'extra' ? `Extra: ${detail}` : detail;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(text);
  };
  ingredients.forEach(value => add(value, 'ingredient'));
  array(item?.extras).forEach(value => add(value, 'extra'));
  array(item?.removedIngredients).forEach(value => add(value, 'removal'));
  const order = half ? ['FULL', 'LEFT', 'RIGHT', 'UNKNOWN'] : ['FULL', 'RIGHT', 'LEFT', 'UNKNOWN'];
  return order.flatMap(key => {
    const rows = groups.get(key) || [];
    const halfName = half && (key === 'LEFT' ? item.leftName : key === 'RIGHT' ? item.rightName : '');
    if (!rows.length && !halfName) return [];
    const heading = half && ['LEFT', 'RIGHT'].includes(key)
      ? `LADO ${key === 'LEFT' ? 1 : 2}${halfName ? `: ${halfName}` : ''}`
      : ({ FULL: 'FULL', RIGHT: 'DERECHA', LEFT: 'IZQUIERDA', UNKNOWN: 'SIN UBICACIÓN' })[key];
    return [heading, ...rows];
  });
}

// Presentation only: never sort or mutate the stored order or recalculate money.
export function getLineDetailRows(item) {
  const custom = String(item?.type || '').toUpperCase() === 'CUSTOM_BUILD' || String(item?.cartLineId || '').startsWith('custom-');
  const half = String(item?.type || '').toUpperCase() === 'HALF_HALF' || Boolean(item?.leftName && item?.rightName) || String(item?.cartLineId || '').startsWith('half-');
  const rows = [];
  if (String(item?.source || '').toLowerCase() === 'incentive_reward' || item?.type === 'INCENTIVE_REWARD') rows.push('Incentivo: premio gratis');
  array(item?.promoItems).forEach(value => rows.push(`${lineQty(value)}x ${lineName(value)}${value.size || value.selectedSize ? ` ${value.size || value.selectedSize}` : ''}`.trim()));
  const direct = array(item?.ingredients);
  const ingredients = direct.length ? direct : array(item?.customDetails?.ingredients);
  if (custom || half) rows.push(...spatialRows(item, ingredients, half));
  else rows.push(...ingredients.map(value => ingredientText(value)).filter(Boolean), ...getLineChangeRows(item));
  if (custom && !ingredients.length) rows.push('Personalizacion sin ingredientes guardados');
  if (custom) {
    const meta = item.customMeta || item.customDetails || {};
    const base = meta.baseProductName || meta.baseName || meta.categoryName || '';
    if (base && !String(item.name || item.pizzaName || item.title || '').toLowerCase().includes(String(base).toLowerCase())) rows.push(`Tipo: ${base}`);
  }
  [...new Set([item?.notes, item?.note, item?.comment].map(value => String(value || '').trim()).filter(Boolean))].forEach(note => rows.push(`Nota: ${note}`));
  return rows;
}
